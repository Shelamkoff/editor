function routeCandidates(href, sourceFile) {
  const urlPath = href.split(/[?#]/, 1)[0]
  if (!urlPath || /^(?:https?:|mailto:|tel:|javascript:)/i.test(urlPath)) return []
  if (urlPath.startsWith('/assets/') || urlPath === '/favicon.ico' || urlPath === '/vp-icons.css') return []

  const sourceRoute = `/${relative(distRoot, sourceFile).replaceAll('\\', '/')}`
  const resolvedRoute = urlPath.startsWith('/')
    ? urlPath
    : `/${normalize(join(dirname(sourceRoute), urlPath)).replaceAll('\\', '/')}`
  const clean = resolvedRoute.replace(/\/$/, '')
  if (clean.endsWith('.html')) return [clean]
  return [
    `${clean || '/index'}.html`,
    `${clean || ''}/index.html`,
  ]
}

for (const htmlFile of htmlFiles) {
  const html = await readFile(htmlFile, 'utf8')
  for (const match of html.matchAll(/\bhref="([^"]+)"/g)) {
    const candidates = routeCandidates(match[1], htmlFile)
    if (candidates.length && !candidates.some(candidate => builtPaths.has(candidate))) {
      failures.push(`${relative(distRoot, htmlFile)} -> ${match[1]}`)
    }
  }
}

