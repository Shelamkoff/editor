import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { dirname, join, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const workspaceRoot = resolve(fileURLToPath(new URL('..', import.meta.url)))
const docsRoot = join(workspaceRoot, 'docs')
const outputRoot = join(docsRoot, 'reference')
const ruOutputRoot = join(docsRoot, 'ru', 'reference')
const generatedCatalogPath = join(docsRoot, '.vitepress', 'readme-catalog.json')

const packageReadmes = []

const readmeCollections = [
  ['plugins', 'editor/plugins', 'Rector block plugins'],
  ['inline-plugins', 'editor/inline-plugins', 'Rector inline plugins'],
  ['renderer/renderers', 'editor/renderers', 'Rector renderers'],
]

function toPosix(value) {
  return value.split(sep).join('/')
}

async function collectReadmes() {
  const specs = packageReadmes.map(([source, route, group]) => ({ source, route, group }))

  for (const [sourceDirectory, routeDirectory, group] of readmeCollections) {
    const absoluteDirectory = join(workspaceRoot, sourceDirectory)
    const rootReadme = join(absoluteDirectory, 'README.md')
    try {
      await readFile(rootReadme)
      specs.push({ source: `${sourceDirectory}/README.md`, route: `${routeDirectory}/index`, group })
    } catch {}

    const entries = await readdir(absoluteDirectory, { withFileTypes: true })
    for (const entry of entries.filter(item => item.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) {
      const source = `${sourceDirectory}/${entry.name}/README.md`
      try {
        await readFile(join(workspaceRoot, source))
        specs.push({ source, route: `${routeDirectory}/${entry.name}`, group })
      } catch {}
    }
  }

  return specs
}

function readTitle(markdown, fallback) {
  return markdown.match(/^#\s+(.+)$/m)?.[1]?.trim() || fallback
}

function normalizeSourceTarget(sourcePath, target) {
  const cleanTarget = target.split('#', 1)[0].split('?', 1)[0]
  const resolved = resolve(dirname(sourcePath), cleanTarget)
  const candidates = [resolved, resolved.replace(`${sep}dist${sep}`, sep)]
  return candidates
}

function rewriteLinks(markdown, sourcePath, routeBySource) {
  return markdown.replace(/\[([^\]]+)]\(([^)]+)\)/g, (match, label, target) => {
    if (/^(?:https?:|mailto:|#)/i.test(target)) return match

    const hash = target.includes('#') ? `#${target.split('#').slice(1).join('#')}` : ''
    for (const candidate of normalizeSourceTarget(sourcePath, target)) {
      const routeEntry = routeBySource.get(candidate)
      if (routeEntry) {
        const localePrefix = routeEntry.locale === 'ru' ? '/ru/reference/' : '/reference/'
        return `[${label}](${localePrefix}${routeEntry.route}${hash})`
      }

      const docsRelative = relative(docsRoot, candidate)
      if (docsRelative && !docsRelative.startsWith(`..${sep}`) && docsRelative.endsWith('.md')) {
        const route = toPosix(docsRelative)
          .replace(/\.md$/i, '')
          .replace(/\/index$/i, '')
        return `[${label}](/${route}${hash})`
      }
    }

    if (/\/(?:LICENSE|NOTICE|THIRD_PARTY_LICENSES\.txt)$/i.test(target.replaceAll('\\', '/'))) {
      return label
    }

    return match
  })
}

const specs = await collectReadmes()
const routeBySource = new Map()
for (const spec of specs) {
  const sourcePath = resolve(workspaceRoot, spec.source)
  const ruSourcePath = join(dirname(sourcePath), 'README.ru.md')
  routeBySource.set(sourcePath, { route: spec.route, locale: 'en' })
  routeBySource.set(sourcePath.replace(`${sep}dist${sep}`, sep), { route: spec.route, locale: 'en' })
  routeBySource.set(ruSourcePath, { route: spec.route, locale: 'ru' })
  routeBySource.set(ruSourcePath.replace(`${sep}dist${sep}`, sep), { route: spec.route, locale: 'ru' })
}

await rm(outputRoot, { recursive: true, force: true })
await rm(ruOutputRoot, { recursive: true, force: true })
await mkdir(outputRoot, { recursive: true })
await mkdir(ruOutputRoot, { recursive: true })

const catalog = []
for (const spec of specs) {
  const sourcePath = resolve(workspaceRoot, spec.source)
  const ruSourcePath = join(dirname(sourcePath), 'README.ru.md')
  const markdown = await readFile(sourcePath, 'utf8')
  const ruMarkdown = await readFile(ruSourcePath, 'utf8').catch(() => {
    throw new Error(`${toPosix(relative(workspaceRoot, ruSourcePath))}: missing Russian README`)
  })
  const title = readTitle(markdown, spec.route.split('/').at(-1))
  const titleRu = readTitle(ruMarkdown, title)
  const destination = join(outputRoot, `${spec.route}.md`)
  const ruDestination = join(ruOutputRoot, `${spec.route}.md`)
  const generated = [
    '---',
    `title: ${JSON.stringify(title)}`,
    'outline: deep',
    'editLink: false',
    '---',
    '',
    '<!-- Generated by scripts/sync-vitepress-readmes.mjs. Edit the source README instead. -->',
    '',
    rewriteLinks(markdown, sourcePath, routeBySource).trim(),
    '',
  ].join('\n')

  await mkdir(dirname(destination), { recursive: true })
  await mkdir(dirname(ruDestination), { recursive: true })
  await writeFile(destination, generated, 'utf8')
  const generatedRu = [
    '---',
    `title: ${JSON.stringify(titleRu)}`,
    'outline: deep',
    'editLink: false',
    '---',
    '',
    '<!-- Generated by scripts/sync-vitepress-readmes.mjs. Edit the source README.ru.md instead. -->',
    '',
    rewriteLinks(ruMarkdown, ruSourcePath, routeBySource).trim(),
    '',
  ].join('\n')
  await writeFile(ruDestination, generatedRu, 'utf8')
  catalog.push({ title, titleRu, route: `/reference/${spec.route}`, group: spec.group, source: toPosix(relative(workspaceRoot, sourcePath)), sourceRu: toPosix(relative(workspaceRoot, ruSourcePath)) })
}

const groups = [...new Set(catalog.map(item => item.group))]
const groupTitlesRu = {
  Rector: 'Rector',
  'Rector block plugins': 'Блочные плагины Rector',
  'Rector inline plugins': 'Инлайн-плагины Rector',
  'Rector renderers': 'Рендереры Rector',
}
const indexLines = [
  '# Extension reference',
  '',
  'This section is generated from extension reference files maintained alongside the source code. The sequential Rector guide is maintained directly in VitePress.',
  '',
]
for (const group of groups) {
  indexLines.push(`## ${group}`, '')
  for (const item of catalog.filter(entry => entry.group === group)) {
    indexLines.push(`- [${item.title}](${item.route})`)
  }
  indexLines.push('')
}
await writeFile(join(outputRoot, 'index.md'), `${indexLines.join('\n').trimEnd()}\n`, 'utf8')
await writeFile(
  join(ruOutputRoot, 'index.md'),
  `${[
    '# Справочник расширений',
    '',
    'Раздел автоматически собирается из русских справочных файлов плагинов и рендереров. Последовательное руководство Rector поддерживается непосредственно в VitePress.',
    '',
    ...groups.flatMap(group => [
      `## ${groupTitlesRu[group] ?? group}`,
      '',
      ...catalog.filter(entry => entry.group === group).map(item => `- [${item.titleRu}](${item.route.replace('/reference/', '/ru/reference/')})`),
      '',
    ]),
  ].join('\n').trimEnd()}\n`,
  'utf8',
)
await writeFile(generatedCatalogPath, `${JSON.stringify(catalog, null, 2)}\n`, 'utf8')

console.log(`Synchronized ${catalog.length} README files into ${toPosix(relative(workspaceRoot, outputRoot))}`)
